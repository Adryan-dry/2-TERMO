CREATE TABLE CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT,
    NOME VARCHAR(120) NOT NULL UNIQUE,
    EMAIL VARCHAR(80) NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);
CREATE TABLE CATEGORIA (
    ID_CATEGORA INT AUTO_INCREMENT,
    NOME VARCHAR (80) NOT NULL UNIQUE,
    CONSTRAINT PK_CATEGORIA (ID_CATEGORIA)
    CONSTRAINT UQ_NOME (NOME)
);
CREATE TABLE PRODUTOS (
    ID_PRODUTOS INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    PRECO DECIMAL(10,2) NOT NULL,
    ID_CATEGORIA INT NOT NULL, 
    CONSTRAINT PK_PRODUTOS PRIMARY KEY (ID_PRODUTOS),
    CONSTRAINT FK_CATEGORIA_PRODUTOS FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA(ID_CATEGORA)
);

CREATE TABLE PEDIDOS (
    ID_PEDIDO INT AUTO_INCREMENT,
    DATA_PEDIDO DATETIME NOT NULL,
    ID_CLIENTE INT NOT NULL,
    CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID_PEDIDO),
    CONSTRAINT FK_CLIENTE_PEDIDO FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE  (ID_CLIENTE)
);

CREATE TABLE ITEM_PEDIDOS (
    ID_ITEM INT AUTO_INCREMENT,
    ID_PEDIDOS INT NOT NULL,
    ID_PRODUTOS INT NOT NULL,
    QUANTIDADE INT NOT NULL CHECK (QUANTIDADE > 0),
    PRECO_UNITARIO DECIMAL (10,2) NOT NULL,
    CONSTRAINT PK_ITEM_PEDIDOS PRIMARY KEY (ID_ITEM),
    CONSTRAINT FK_PEDIDOS_ITEMP FOREIGN KEY (ID_PEDIDOS) REFERENCES PEDIDOS (ID_PEDIDOS),
    CONSTRAINT FK_PRODUTOS_ITEMP FOREIGN KEY (ID_PRODUTOS) REFERENCES PRODUTOS (ID_PRODUTOS)
);

CREATE TABLE FORNECEDOR (
    ID_FORNECEDOR INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    TELEFONE VARCHAR(20),
    CONSTRAINT PK_FORNECEDOR PRIMARY KEY (ID_FORNECEDOR)
);


CREATE TABLE FORNECEDOR_PRODUTO (
    ID_FPRODS INT AUTO_INCREMENT,
    ID_FORNECEDOR INT NOT NULL,
    ID_PRODUTOS INT NOT NULL,
    PRECO_COMPRA DECIMAL(10,2) NOT NULL,
    PRAZO_ENTREGA_DIAS INT,
    CONSTRAINT PK_FORNECEDOR_PRODUTOS PRIMARY KEY (ID_FPRODS),
    CONSTRAINT FK_FORNECEDOR_PRODUTOS FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR (ID_FORNECEDOR),
    CONSTRAINT FK_PRODUTOS_FORNECEDOR FOREIGN KEY (ID_PRODUTOS) REFERENCES PRODUTOS (ID_PRODUTOS)
);
